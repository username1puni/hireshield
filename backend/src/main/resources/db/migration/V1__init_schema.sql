CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(255)  NOT NULL UNIQUE,
    password_hash VARCHAR(100)  NOT NULL,
    role          VARCHAR(20)   NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE model_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     VARCHAR(50)  NOT NULL UNIQUE,
    algorithm   VARCHAR(100) NOT NULL,
    trained_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    precision_score NUMERIC(6, 4),
    recall_score    NUMERIC(6, 4),
    f1_score        NUMERIC(6, 4),
    pr_auc          NUMERIC(6, 4),
    threshold       NUMERIC(6, 4),
    file_path   VARCHAR(255) NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE analyses (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT REFERENCES users (id) ON DELETE CASCADE,
    input_type       VARCHAR(10)  NOT NULL,
    raw_text         TEXT         NOT NULL,
    source_url       VARCHAR(2048),
    recruiter_email  VARCHAR(255),
    domain           VARCHAR(255),
    final_score      INT          NOT NULL,
    risk_level       VARCHAR(10)  NOT NULL,
    rule_score       INT          NOT NULL,
    ml_probability   NUMERIC(6, 4) NOT NULL,
    trust_score      INT          NOT NULL,
    explanation      TEXT,
    explanation_source VARCHAR(20),
    model_version_id BIGINT REFERENCES model_versions (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_analyses_user_created ON analyses (user_id, created_at);

CREATE TABLE analysis_flags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT       NOT NULL REFERENCES analyses (id) ON DELETE CASCADE,
    rule_code   VARCHAR(40)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    points      INT          NOT NULL,
    evidence    VARCHAR(500)
);

CREATE INDEX idx_flags_analysis ON analysis_flags (analysis_id);

CREATE TABLE uploaded_files (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT       NOT NULL REFERENCES analyses (id) ON DELETE CASCADE,
    file_name   VARCHAR(255) NOT NULL,
    mime_type   VARCHAR(100) NOT NULL,
    size_bytes  BIGINT       NOT NULL,
    sha256      VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE domain_checks (
    domain           VARCHAR(255) PRIMARY KEY,
    registered_on    DATE,
    age_days         INT,
    registrar        VARCHAR(255),
    has_mx           BOOLEAN,
    free_provider    BOOLEAN NOT NULL DEFAULT FALSE,
    lookalike_of     VARCHAR(100),
    checked_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE link_checks (
    url_hash     VARCHAR(64) PRIMARY KEY,
    url          VARCHAR(2048) NOT NULL,
    verdict      VARCHAR(20)   NOT NULL,
    reasons      VARCHAR(1000),
    checked_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE scam_reports (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    company_name VARCHAR(200),
    email        VARCHAR(255),
    phone        VARCHAR(30),
    upi_id       VARCHAR(100),
    domain       VARCHAR(255),
    platform     VARCHAR(50),
    amount_lost  NUMERIC(12, 2),
    description  TEXT NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at  TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_reports_status ON scam_reports (status, created_at);

CREATE TABLE blacklist_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_type   VARCHAR(10)  NOT NULL,
    entry_value  VARCHAR(255) NOT NULL,
    report_count INT          NOT NULL DEFAULT 1,
    first_seen   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_blacklist_type_value UNIQUE (entry_type, entry_value)
);

CREATE TABLE feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT  NOT NULL REFERENCES analyses (id) ON DELETE CASCADE,
    user_id     BIGINT  REFERENCES users (id) ON DELETE CASCADE,
    correct     BOOLEAN NOT NULL,
    comment     VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_feedback_analysis_user UNIQUE (analysis_id, user_id)
);

CREATE TABLE rule_config (
    code        VARCHAR(40)  PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description VARCHAR(500) NOT NULL,
    points      INT          NOT NULL,
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE
);
